"""Writes Tests/Generated/TestSounds.h: short test signals encoded by the ffmpeg on the machine, and ffmpeg's own decode of
the lossy ones as reference. Run from the repository root: python Tools/GenerateTestSounds.py [path to ffmpeg]."""

import os
import subprocess
import sys
import tempfile

FFMPEG = sys.argv[1] if len(sys.argv) > 1 else "ffmpeg"
RATE = 44100
SECONDS = 0.1
MONO = f"sine=frequency=440:sample_rate={RATE}:duration={SECONDS}"
STEREO = f"aevalsrc=0.6*sin(440*2*PI*t)|0.4*sin(660*2*PI*t)+0.2*sin(3000*2*PI*t):s={RATE}:d={SECONDS}"
SURROUND = f"aevalsrc=0.5*sin(200*2*PI*t)|0.5*sin(300*2*PI*t)|0.5*sin(400*2*PI*t)|0.5*sin(50*2*PI*t)|0.5*sin(500*2*PI*t)|0.5*sin(600*2*PI*t):s=48000:d={SECONDS}:c=5.1"

# name, source, extension, ffmpeg output options, whether the reference decode is stored
SOUNDS = [
    ("WavFloat32", MONO, "wav", ["-c:a", "pcm_f32le"], False),
    ("WavFloat64", MONO, "wav", ["-c:a", "pcm_f64le"], False),
    ("WavU8", MONO, "wav", ["-c:a", "pcm_u8"], False),
    ("WavS16", MONO, "wav", ["-c:a", "pcm_s16le"], False),
    ("WavS24", MONO, "wav", ["-c:a", "pcm_s24le"], False),
    ("WavS32", MONO, "wav", ["-c:a", "pcm_s32le"], False),
    ("WavRf64", MONO, "wav", ["-c:a", "pcm_s16le", "-rf64", "always"], False),
    ("W64", MONO, "w64", ["-c:a", "pcm_s16le"], False),
    ("WavALaw", MONO, "wav", ["-c:a", "pcm_alaw"], True),
    ("WavMuLaw", MONO, "wav", ["-c:a", "pcm_mulaw"], True),
    ("WavImaAdpcm", MONO, "wav", ["-c:a", "adpcm_ima_wav"], True),
    ("WavMsAdpcm", MONO, "wav", ["-c:a", "adpcm_ms"], True),
    ("WavStereoS16", STEREO, "wav", ["-c:a", "pcm_s16le"], True),
    ("Flac16", STEREO, "flac", ["-c:a", "flac", "-sample_fmt", "s16"], True),
    ("Flac24", MONO, "flac", ["-c:a", "flac", "-sample_fmt", "s32", "-bits_per_raw_sample", "24"], False),
    ("Flac51", SURROUND, "flac", ["-c:a", "flac", "-sample_fmt", "s16"], True),
    ("Mp3", STEREO, "mp3", ["-c:a", "libmp3lame", "-b:a", "128k"], True),
    ("Mp3Mono22k", MONO, "mp3", ["-c:a", "libmp3lame", "-ar", "22050", "-b:a", "64k"], True),
    ("Ogg51", SURROUND, "ogg", ["-c:a", "libvorbis", "-q:a", "4"], True),
    ("Ogg", STEREO, "ogg", ["-c:a", "libvorbis", "-q:a", "3", "-metadata", "LOOPSTART=1000", "-metadata", "LOOPLENGTH=2000"], True),
]


def run(args):
    subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-y"] + args, check=True)


def array(name, data, per_line=24):
    lines = [f"    inline constexpr unsigned char k{name}[] = {{"]
    for i in range(0, len(data), per_line):
        lines.append("        " + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) + ",")
    lines.append("    };")
    return "\n".join(lines)


def main():
    out = [
        "#pragma once",
        "",
        "// Generated by Tools/GenerateTestSounds.py with ffmpeg: test signals in every format, and ffmpeg's own decode",
        "// of the lossy ones (k<Name>Reference, interleaved little endian float32). Do not edit.",
        "namespace helix::audio::testing",
        "{",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, source, ext, options, reference in SOUNDS:
            path = os.path.join(tmp, f"{name}.{ext}")
            run(["-f", "lavfi", "-i", source] + options + [path])
            data = open(path, "rb").read()
            out.append(array(name, data))
            if reference:
                raw = os.path.join(tmp, f"{name}.raw")
                run(["-i", path, "-f", "f32le", "-c:a", "pcm_f32le", raw])
                out.append(array(f"{name}Reference", open(raw, "rb").read()))
            print(f"{name}: {len(data)} bytes")
    out.append("}")
    out.append("")
    target = os.path.join("Tests", "Generated", "TestSounds.h")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
